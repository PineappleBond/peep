/**
 * 根据天干地支索引计算纳音。
 *
 * @param stem 天干索引（0-9）
 * @param branch 地支索引（0-11）
 * @returns 纳音名称（如"海中金"）
 */
export function getNaYin(stem: number, branch: number): string {
  // 六十甲子序号：n ≡ stem (mod 10), n ≡ branch (mod 12)
  // 由 CRT 得：n = (6*stem - 5*branch + 60) % 60
  const sexagenary = (((6 * stem - 5 * branch) % 60) + 60) % 60;
  return NAYIN_TABLE[sexagenary];
}

/**
 * 批量计算 12 个地支对应天盘纳音（每个地支取日干配该支的纳音）。
 *
 * @param dayStem 日干
 * @param _heavenBoard 天盘（当前简化版不使用，保留签名一致性）
 * @returns Record<number, string>，key 为地盘支索引，value 为日干配该支的纳音
 */
export function getBoardNaYin(dayStem: number, _heavenBoard: number[]): Record<number, string> {
  const result: Record<number, string> = {};
  // 地盘每宫的天盘纳音：需要遁干
  // 大六壬纳音通常以四课/三传干支计算，地盘每宫用日干遁得
  // 此处为简化版：地盘 12 支按"日干遁支"得干支组合的纳音
  // 即日干配地盘支的纳音
  for (let i = 0; i < 12; i++) {
    result[i] = getNaYin(dayStem, i);
  }
  return result;
}
